    p = sub.add_parser("info", parents=[common], help="parameters and price of a model")
    p.add_argument("model_id")
    p.set_defaults(func=cmd_info)

    p = sub.add_parser("prices", parents=[common, filters], help="query prices via estimate (free)")
    p.set_defaults(func=cmd_prices)

