def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="hf", description="The Higgsfield API from the terminal.")
    # Parent parser for options that should be allowed on every subcommand.
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--verbose", "-v", action="store_true", help="more output, stack traces on errors")

    sub = parser.add_subparsers(dest="command", required=True)

    # Options for all commands that create a job (estimate, submit, run).
    generation = argparse.ArgumentParser(add_help=False)
    generation.add_argument("model_id", help="e.g. higgsfield-ai/soul/standard")
    generation.add_argument("--prompt", required=True)
    generation.add_argument("--image-url", help="input image: URL or local file (gets uploaded)")
    generation.add_argument("--image-urls", nargs="+", metavar="IMAGE",
                            help="several input images (for edit models), URLs or local files")
    generation.add_argument("--character", help="trained Soul ID character (name or ID)")
    generation.add_argument(
        "--param", action="append", default=[], metavar="KEY=VALUE",
        help="additional model parameter, can be repeated",
    )

    p = sub.add_parser("estimate", parents=[common, generation], help="estimate the cost up front")
    p.set_defaults(func=cmd_estimate)

    p = sub.add_parser("submit", parents=[common, generation], help="submit a job")
    p.set_defaults(func=cmd_submit)

    p = sub.add_parser("status", parents=[common], help="status of a job")
    p.add_argument("request_id")
    p.add_argument("--urls", action="store_true", help="also print the result URLs")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("cancel", parents=[common], help="cancel a job (only while 'queued')")
    p.add_argument("request_id")
    p.set_defaults(func=cmd_cancel)

    p = sub.add_parser("upload", parents=[common], help="upload a local file, prints its public URL")
    p.add_argument("file", type=Path)
