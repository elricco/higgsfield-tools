# --- Constants --------------------------------------------------------------

BASE_URL = "https://api.higgsfield.ai"
# The complete docs in one text file – contains the parameters of all models.
DOCS_FULL_URL = "https://docs.higgsfield.ai/llms-full.txt"

# Statuses at which a job is finished (success or failure).
TERMINAL_STATUSES = {"completed", "failed", "nsfw", "canceled"}

# Path(__file__).parent is the folder this file lives in.
# That way the CLI finds models.json even when called from another folder.
PROJECT_DIR = Path(__file__).parent
# Own notes and default parameters for tested models (maintained by hand).
MODELS_FILE = PROJECT_DIR / "models.json"
# Generated by 'hf catalog update' and 'hf prices'.
CATALOG_FILE = PROJECT_DIR / "catalog.json"
PRICES_FILE = PROJECT_DIR / "prices.json"
# Trained Soul ID characters: name -> ID (the API cannot list them).
CHARACTERS_FILE = PROJECT_DIR / "characters.json"
ENV_FILE = PROJECT_DIR / ".env"
# Remembers which model belongs to which request_id (for file names).
HISTORY_FILE = PROJECT_DIR / ".hf-history.json"

# Maximum number of seconds a single HTTP call may take.
HTTP_TIMEOUT = 30
# How many times a call is attempted in total on temporary errors.
MAX_ATTEMPTS = 4
# HTTP status codes for which another attempt is worthwhile.
RETRY_STATUS_CODES = {429, 500, 502, 503, 504}
# Polling as recommended by the docs: start at 2 s, slowly increase to 10 s.
POLL_START_DELAY = 2.0
POLL_MAX_DELAY = 10.0
# File types the upload accepts according to the docs.
UPLOAD_CONTENT_TYPES = {"image/jpeg", "image/png", "image/webp", "image/gif", "audio/wav", "audio/x-wav", "video/mp4"}
# Uploads of large videos may take longer than normal API calls.
UPLOAD_TIMEOUT = 300
# File extensions in case the URL does not reveal one.
FALLBACK_EXTENSIONS = {"images": ".jpg", "video": ".mp4", "audio": ".mp3", "audios": ".mp3"}


# --- Errors and output ------------------------------------------------------


class CliError(Exception):
    """An expected error: printed as a short message, without a stack trace."""

    def __init__(self, message: str, exit_code: int = 1):
        super().__init__(message)
        self.exit_code = exit_code


def print_json(data: dict) -> None:
    """Prints a dictionary as a single line of JSON."""
    # ensure_ascii=False keeps non-ASCII characters readable (ü instead of \u00fc).
    print(json.dumps(data, ensure_ascii=False))


# --- Configuration ----------------------------------------------------------


def load_dotenv(path: Path) -> None:
    """Reads KEY=VALUE lines from a .env file into the environment variables.

    Variables that are already set are not overwritten, i.e. an
    'export HF_API_KEY=...' in the terminal takes precedence over the file.
    """
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        # Skip empty lines, comments and lines without '='.
        if not line or line.startswith("#") or "=" not in line:
            continue
        # split("=", 1) only splits at the first '=' – the secret itself may contain '='.
        name, value = line.split("=", 1)
        name = name.strip().removeprefix("export ").strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(name, value)


def load_credentials() -> tuple[str, str]:
    """Reads key and secret from the environment variables.

    The values are never printed – not even in error messages.
    """
    key = os.environ.get("HF_API_KEY")
    secret = os.environ.get("HF_API_SECRET")
    if not key or not secret:
        raise CliError("HF_API_KEY and HF_API_SECRET must be set.", exit_code=2)
    if key.startswith("your-") or secret.startswith("your-"):
        raise CliError(".env still contains the placeholders from .env.example – enter real values.", exit_code=2)
    return key, secret


def load_models() -> dict:
    """Reads the local model list from models.json."""
    try:
        return json.loads(MODELS_FILE.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise CliError(f"{MODELS_FILE.name} not found.")
    except json.JSONDecodeError as error:
        raise CliError(f"{MODELS_FILE.name} is not valid JSON: {error}")


def read_json_file(path: Path, default):
    """Reads a JSON file or returns default if it does not exist."""
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise CliError(f"{path.name} is not valid JSON.")


def write_json_file(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_catalog() -> dict:
    data = read_json_file(CATALOG_FILE, None)
    if data is None:
        raise CliError("No catalog yet. Run 'hf catalog update' first.")
    return data


def load_history() -> dict:
    """Reads {request_id: model_id} from the history file (empty if it does not exist)."""
    if not HISTORY_FILE.exists():
        return {}
    try:
        return json.loads(HISTORY_FILE.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def remember_request(request_id: str, model_id: str) -> None:
    history = load_history()
    history[request_id] = model_id
    HISTORY_FILE.write_text(json.dumps(history, indent=2), encoding="utf-8")


# --- Parameters -------------------------------------------------------------


def parse_param(text: str) -> tuple[str, object]:
    """Splits 'key=value' into ('key', value).

    The value is read as JSON if that works: 'duration=5' gives the
    number 5, 'enhance_prompt=true' the boolean True. Everything else stays text.
    """
    if "=" not in text:
        raise CliError(f"Parameter '{text}' is not of the form key=value.")
    key, raw_value = text.split("=", 1)
    try:
        value = json.loads(raw_value)
    except json.JSONDecodeError:
        value = raw_value
    return key.strip(), value


def build_payload(args: argparse.Namespace) -> dict:
    """Builds the JSON body for a generation.

    Order (later ones win): model defaults from models.json,
    then --prompt/--image-url, then --param.
    """
    model_info = load_models().get(args.model_id, {})
    # dict(...) creates a copy so that we do not modify the loaded defaults.
    payload = dict(model_info.get("defaults", {}))
    payload["prompt"] = args.prompt
    if args.image_url:
        payload["image_url"] = resolve_input_url(args.image_url)
    if args.image_urls:
        # A "list comprehension": applies resolve_input_url to every element.
        payload["image_urls"] = [resolve_input_url(value) for value in args.image_urls]
    if args.character:
        payload["custom_reference_id"] = find_character(args.character)["id"]
        payload.setdefault("custom_reference_strength", 1.0)
    for text in args.param:
        key, value = parse_param(text)
        payload[key] = value
    return payload


# --- HTTP -------------------------------------------------------------------


def make_session() -> requests.Session:
    """Creates a session that sends the auth header with every call."""
    key, secret = load_credentials()
    session = requests.Session()
    session.headers["Authorization"] = f"Key {key}:{secret}"
    return session


def retry_delay(attempt: int, retry_after: str | None = None) -> float:
    """Wait time before the next attempt: 1, 2, 4 ... seconds plus some randomness.

    If the server sends a Retry-After header, we stick to it.
    """
    if retry_after and retry_after.isdigit():
        return float(retry_after)
    return 2 ** (attempt - 1) + random.uniform(0, 0.5)


def describe_error(response: requests.Response) -> str:
    """Turns an error response into a short, readable message."""
    try:
        detail = response.json().get("detail")
    except (ValueError, AttributeError):
        return response.text[:200] or response.reason
    if isinstance(detail, dict):
        # e.g. {"code": "account_queue_full", "message": "..."}
        return detail.get("message") or json.dumps(detail)
    if isinstance(detail, list):
        # Validation errors: list of {"loc": [...], "msg": "..."}
        parts = []
        for item in detail:
            location = ".".join(str(x) for x in item.get("loc", []) if x not in ("body", ""))
            message = str(item.get("msg", "")).lstrip(": ")
            parts.append(f"{location}: {message}" if location else message)
        return "; ".join(parts)
    # For missing required fields the text starts with ": " (empty field path).
    return str(detail).lstrip(": ")


def api_request(
    session: requests.Session,
    method: str,
    path: str,
    json_body: dict | None = None,
    headers: dict | None = None,
) -> dict:
    """Sends an API call and returns the JSON response.

    - Timeout on every call.
    - New attempts on network errors, 429 and 5xx (with backoff).
    - No new attempts on other 4xx – something is wrong with the request.
    """
    url = path if path.startswith("http") else BASE_URL + path
    for attempt in range(1, MAX_ATTEMPTS + 1):
        is_last_attempt = attempt == MAX_ATTEMPTS
        try:
            response = session.request(method, url, json=json_body, headers=headers, timeout=HTTP_TIMEOUT)
        except (requests.ConnectionError, requests.Timeout) as error:
            if is_last_attempt:
                raise CliError(f"Network error after {MAX_ATTEMPTS} attempts: {type(error).__name__}")
            time.sleep(retry_delay(attempt))
            continue

        if response.status_code in RETRY_STATUS_CODES and not is_last_attempt:
            time.sleep(retry_delay(attempt, response.headers.get("Retry-After")))
            continue

        if response.status_code >= 400:
            raise CliError(f"HTTP {response.status_code}: {describe_error(response)}")

        # Some responses (e.g. cancel) have no content.
        return response.json() if response.content else {}

    # Never reached – the loop always ends with return or raise.
    raise CliError("Unexpected error in api_request.")


def download_file(url: str, target: Path) -> None:
    """Downloads a file in chunks (saves memory for large videos).

    Deliberately without the session: the credentials only go to api.higgsfield.ai,
    not to the CDN that hosts the results.
    """
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            # 'with' makes sure the connection is closed safely afterwards.
            with requests.get(url, stream=True, timeout=HTTP_TIMEOUT) as response:
                if response.status_code in RETRY_STATUS_CODES and attempt < MAX_ATTEMPTS:
                    time.sleep(retry_delay(attempt))
                    continue
                if response.status_code >= 400:
                    raise CliError(f"Download failed: HTTP {response.status_code}")
                with target.open("wb") as file:
                    for chunk in response.iter_content(chunk_size=1024 * 1024):
                        file.write(chunk)
                return
        except (requests.ConnectionError, requests.Timeout) as error:
            if attempt == MAX_ATTEMPTS:
                raise CliError(f"Download failed: {type(error).__name__}")
            time.sleep(retry_delay(attempt))


# --- Upload -----------------------------------------------------------------


def guess_content_type(path: Path) -> str:
    """Determines the file type from the extension, e.g. .jpg -> image/jpeg."""
    # guess_type returns a tuple (type, encoding) – we do not need the encoding.
    content_type, _ = mimetypes.guess_type(path.name)
    if content_type not in UPLOAD_CONTENT_TYPES:
        allowed = ", ".join(sorted(UPLOAD_CONTENT_TYPES))
        raise CliError(f"File type of '{path.name}' is not supported ({content_type}). Allowed: {allowed}")
    return content_type


def upload_file(session: requests.Session, path: Path) -> str:
    """Uploads a local file to Higgsfield and returns its public URL.

    Flow according to the docs:
    1. Request a presigned upload URL from the API.
    2. Send the file via PUT directly to the storage – with exactly the
       headers from the response and WITHOUT our credentials.
    3. Use the public_url as image_url/video_url in the generation.
    """
    if not path.is_file():
        raise CliError(f"File not found: {path}")
    content_type = guess_content_type(path)
    upload = api_request(session, "POST", "/files/generate-upload-url",
                         json_body={"content_type": content_type})

    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            # requests.put instead of session.put: no Authorization header to the storage.
            response = requests.put(upload["upload_url"], data=path.read_bytes(),
                                    headers=upload.get("upload_headers", {}), timeout=UPLOAD_TIMEOUT)
        except (requests.ConnectionError, requests.Timeout) as error:
            if attempt == MAX_ATTEMPTS:
                raise CliError(f"Upload failed: {type(error).__name__}")
            time.sleep(retry_delay(attempt))
            continue
        if response.status_code in RETRY_STATUS_CODES and attempt < MAX_ATTEMPTS:
            time.sleep(retry_delay(attempt))
            continue
        if response.status_code >= 400:
            raise CliError(f"Upload failed: HTTP {response.status_code}")
        return upload["public_url"]
    raise CliError("Unexpected error in upload_file.")


def resolve_input_url(value: str, session: requests.Session | None = None) -> str:
    """Returns URLs unchanged, uploads local files first."""
    if value.startswith(("http://", "https://")):
        return value
    # expanduser() turns "~/Pictures/x.jpg" into a full path.
    return upload_file(session or make_session(), Path(value).expanduser())


# --- Characters (Soul ID) ---------------------------------------------------


def load_characters() -> dict:
    return read_json_file(CHARACTERS_FILE, {})


def find_character(name_or_id: str) -> dict:
    """Finds a character by its name (case-insensitive) or its ID."""
    for name, character in load_characters().items():
        if name.lower() == name_or_id.lower() or character["id"] == name_or_id:
            return {"name": name, **character}
    raise CliError(f"Unknown character '{name_or_id}'. See 'hf character list'.")


def save_character(name: str, data: dict) -> None:
    characters = load_characters()
    # Keep existing fields, overwrite them with the new ones.
    characters[name] = {**characters.get(name, {}), **data}
    write_json_file(CHARACTERS_FILE, characters)


def character_payload(name: str, model_version: str, image_urls: list[str]) -> dict:
    """Body for POST /v1/custom-references according to the docs."""
    return {
        "name": name,
        "model_version": model_version,
        "input_images": [{"type": "image_url", "image_url": url} for url in image_urls],
    }


def cmd_character_create(args: argparse.Namespace) -> dict:
    if not 1 <= len(args.images) <= 100:
        raise CliError("Soul ID needs 1 to 100 images.")
    if args.name.lower() in (name.lower() for name in load_characters()):
        raise CliError(f"A character '{args.name}' already exists.")
    session = make_session()
    urls = [resolve_input_url(value, session) for value in args.images]
    result = api_request(session, "POST", "/v1/custom-references",
                         json_body=character_payload(args.name, args.model_version, urls))
    save_character(args.name, {
        "id": result["id"],
        "model_version": args.model_version,
        "status": result.get("status"),
        "created": date.today().isoformat(),
        "images": [str(value) for value in args.images],
    })
    return {"name": args.name, "id": result["id"], "status": result.get("status")}


def cmd_character_status(args: argparse.Namespace) -> dict:
    character = find_character(args.name)
    result = api_request(make_session(), "GET", f"/v1/custom-references/{character['id']}")
    save_character(character["name"], {"status": result.get("status")})
    output = {"name": character["name"], "id": character["id"], "status": result.get("status")}
    if result.get("status") == "failed":
        output["error"] = result.get("error") or "Training failed."
    if args.verbose:
        output["response"] = result
    return output


def cmd_character_add(args: argparse.Namespace) -> dict:
    """Registers an already trained character locally (e.g. from another machine)."""
    if args.name.lower() in (name.lower() for name in load_characters()):
        raise CliError(f"A character '{args.name}' already exists.")
    # Check that the ID belongs to this account – costs nothing.
    result = api_request(make_session(), "GET", f"/v1/custom-references/{args.id}")
    save_character(args.name, {
        "id": args.id,
        "model_version": args.model_version,
        "status": result.get("status"),
        "added": date.today().isoformat(),
    })
    return {"name": args.name, "id": args.id, "status": result.get("status")}


def cmd_character_list(args: argparse.Namespace) -> dict:
    return {
        "characters": [
            {"name": name, "id": c["id"], "model_version": c.get("model_version"), "status": c.get("status")}
            for name, c in load_characters().items()
        ]
    }


# --- Results ----------------------------------------------------------------


def compact_status(result: dict) -> dict:
    """Reduces a status response to the important fields."""
    output = {"request_id": result.get("request_id"), "status": result.get("status")}
    if result.get("error"):
        output["error"] = result["error"]
    elif result.get("status") in {"failed", "nsfw", "canceled"}:
        # So that main() returns a non-zero exit code.
        output["error"] = f"Job ended with status '{result['status']}'"
    return output


def extract_outputs(result: dict) -> list[tuple[str, str]]:
    """Collects all result URLs as a list of (field name, url).

    Images come as a list ("images"), videos as a single object ("video").
    "audio" and "audios" can contain the same file – duplicates are dropped.
    """
    outputs = []
    seen = set()
    for field in ("images", "video", "audio", "audios"):
        value = result.get(field)
        if not value:
            continue
        # Wrap a single object in a list so that both cases work the same way.
        items = value if isinstance(value, list) else [value]
        for item in items:
            url = item.get("url")
            if url and url not in seen:
                seen.add(url)
                outputs.append((field, url))
    return outputs


def output_filename(model_id: str, request_id: str, field: str, url: str,
                    index: int, total: int, day: date) -> str:
    """Builds the file name: <date>_<model>_<request_id>[_<n>].<extension>"""
    model_slug = model_id.replace("/", "-")
    extension = Path(urlparse(url).path).suffix or FALLBACK_EXTENSIONS.get(field, "")
    number = f"_{index}" if total > 1 else ""
    return f"{day:%Y-%m-%d}_{model_slug}_{request_id}{number}{extension}"


def poll_until_done(session: requests.Session, request_id: str, timeout: int) -> dict:
    """Polls the status until the job is finished or the time runs out."""
    # time.monotonic() is a clock that never jumps backwards – ideal for measuring time.
    deadline = time.monotonic() + timeout
    delay = POLL_START_DELAY
    while True:
        result = api_request(session, "GET", f"/requests/{request_id}/status")
        if result.get("status") in TERMINAL_STATUSES:
            return result
        if time.monotonic() + delay > deadline:
            raise CliError(
                f"Timeout after {timeout} s, job {request_id} is still running "
                f"(status '{result.get('status')}'). Continue later with 'wait'."
            )
        # Some randomness (jitter) so that many clients do not poll in lockstep.
        time.sleep(delay + random.uniform(0, 0.5))
        delay = min(delay * 1.5, POLL_MAX_DELAY)


def save_outputs(result: dict, model_id: str, out_dir: Path) -> list[str]:
    """Downloads all results and returns the file paths."""
    outputs = extract_outputs(result)
    if not outputs:
        raise CliError("The response contains no result files.")
    # parents=True also creates intermediate folders, exist_ok=True ignores existing ones.
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    # enumerate(..., start=1) yields number and element: (1, a), (2, b), ...
    for index, (field, url) in enumerate(outputs, start=1):
        name = output_filename(model_id, result["request_id"], field, url,
                               index, len(outputs), date.today())
        target = out_dir / name
        download_file(url, target)
        paths.append(str(target))
    return paths


# --- Commands ---------------------------------------------------------------
# Every function receives the parsed arguments (args) and returns a dictionary.
# main() takes care of the output.


def cmd_estimate(args: argparse.Namespace) -> dict:
    payload = build_payload(args)
    result = api_request(make_session(), "POST", f"/estimate/{args.model_id}", json_body=payload)
    output = {"model": args.model_id, "usd": result.get("usd")}
    # Token-based models return a pricing description instead of a number.
    if result.get("pricing_description"):
        output["pricing"] = result["pricing_description"]
    if args.verbose:
        output["payload"] = payload
        output["response"] = result
    return output


def submit_generation(session: requests.Session, args: argparse.Namespace) -> dict:
    """Submits a job and remembers the model for the request_id."""
    payload = build_payload(args)
    # One idempotency key per job: if api_request repeats the call after a
    # timeout, the server recognizes it and does not create a second (paid) job.
    headers = {"Idempotency-Key": str(uuid.uuid4())}
    result = api_request(session, "POST", f"/{args.model_id}", json_body=payload, headers=headers)
    remember_request(result["request_id"], args.model_id)
    return result


def cmd_submit(args: argparse.Namespace) -> dict:
    result = submit_generation(make_session(), args)
    return result if args.verbose else compact_status(result)


def cmd_status(args: argparse.Namespace) -> dict:
    result = api_request(make_session(), "GET", f"/requests/{args.request_id}/status")
    if args.verbose:
        return result
    output = compact_status(result)
    if args.urls:
        # Public result URLs, e.g. as --image-url for image-to-video (valid for 7 days).
        output["urls"] = [url for _, url in extract_outputs(result)]
    return output


def cmd_upload(args: argparse.Namespace) -> dict:
    return {"file": str(args.file), "url": upload_file(make_session(), args.file)}


def cmd_cancel(args: argparse.Namespace) -> dict:
    try:
        api_request(make_session(), "POST", f"/requests/{args.request_id}/cancel")
    except CliError as error:
        if str(error).startswith("HTTP 400"):
            # According to the docs: 400 means the job is already running and can no longer be canceled.
            raise CliError(f"Job {args.request_id} is already running and can no longer be canceled.")
        raise
    return {"request_id": args.request_id, "status": "canceled"}


def cmd_wait(args: argparse.Namespace) -> dict:
    result = poll_until_done(make_session(), args.request_id, args.timeout)
    return result if args.verbose else compact_status(result)


def cmd_download(args: argparse.Namespace) -> dict:
    result = api_request(make_session(), "GET", f"/requests/{args.request_id}/status")
    if result.get("status") != "completed":
        output = compact_status(result)
        output.setdefault("error", f"Job is not finished yet (status '{result.get('status')}').")
        return output
    model_id = load_history().get(args.request_id, "unknown")
    files = save_outputs(result, model_id, args.out)
    return {"request_id": args.request_id, "status": "completed", "files": files}


def cmd_run(args: argparse.Namespace) -> dict:
    session = make_session()
    submitted = submit_generation(session, args)
    result = poll_until_done(session, submitted["request_id"], args.timeout)
    if result.get("status") != "completed":
        return compact_status(result)
    files = save_outputs(result, args.model_id, args.out)
    return {"request_id": result["request_id"], "status": "completed", "files": files}


def filtered_models(args: argparse.Namespace) -> dict:
    """All catalog models that match --output/--op/--search."""
    models = load_catalog()["models"]
    return {
        model_id: model
        for model_id, model in models.items()
        if (model.get("listed") or args.all)
        and catalog.matches(model_id, model, args.output, args.op, args.search)
    }


def price_summary(price: dict | None) -> dict:
    """Short form of a price entry for the output."""
    if not price:
        return {}
    if price.get("usd") is not None:
        return {"usd": price["usd"]}
    if price.get("pricing"):
        return {"usd": None, "pricing": "variable (see 'hf info')"}
    return {"usd": None, "price_error": price.get("error")}


def cmd_models(args: argparse.Namespace) -> dict:
    models = filtered_models(args)
    prices = read_json_file(PRICES_FILE, {})
    notes = load_models()
    rows = []
    for model_id, model in models.items():
        row = {"id": model_id, "title": model.get("title"), "ops": model.get("operations")}
        row.update(price_summary(prices.get(model_id)))
        if notes.get(model_id, {}).get("tested"):
            row["tested"] = True
        if not model.get("documented"):
            row["documented"] = False
        rows.append(row)
    if args.sort == "price":
        # sorted(..., key=...) sorts by the value the key function returns.
        rows.sort(key=lambda row: catalog.price_sort_key(prices.get(row["id"])))
    if args.limit:
        rows = rows[:args.limit]
    return {"count": len(rows), "models": rows}


def cmd_info(args: argparse.Namespace) -> dict:
    models = load_catalog()["models"]
    model = models.get(args.model_id)
    if model is None:
        raise CliError(f"Model '{args.model_id}' is not in the catalog. Tip: 'hf models --search ...'")
    output = {"id": args.model_id, **model}
    if not args.verbose:
        output.pop("description", None)
    price = read_json_file(PRICES_FILE, {}).get(args.model_id)
    if price:
        output["price"] = price
    own_notes = load_models().get(args.model_id)
    if own_notes:
        output["own_notes"] = own_notes
    return output


def check_api() -> str:
    """Asks for the status of a made-up request ID: 404 means the credentials work."""
    key, secret = load_credentials()
    try:
        # Deliberately without api_request: no retries, short timeout – a check should be fast.
        response = requests.get(f"{BASE_URL}/requests/00000000-0000-0000-0000-000000000000/status",
                                headers={"Authorization": f"Key {key}:{secret}"}, timeout=10)
    except requests.RequestException as error:
        return f"unreachable ({type(error).__name__}) – firewall? allow *.higgsfield.ai"
    if response.status_code == 404:
        return "ok"
    if response.status_code == 401:
        return "wrong credentials (401)"
    return f"unexpected: HTTP {response.status_code}"


def check_docs() -> str:
    try:
        requests.head(DOCS_FULL_URL, timeout=10).raise_for_status()
    except requests.RequestException as error:
        return f"unreachable ({type(error).__name__}) – only needed for 'catalog update'"
    return "ok"


def cmd_doctor(args: argparse.Namespace) -> dict:
    checks = {}
    try:
        load_credentials()
        checks["credentials"] = "ok"
        checks["api"] = check_api()
    except CliError as error:
        checks["credentials"] = str(error)
    checks["docs"] = check_docs()
    catalog_data = read_json_file(CATALOG_FILE, None)
    checks["catalog"] = f"as of {catalog_data['updated']}" if catalog_data else "missing – 'hf catalog update'"
    output = {"checks": checks}
    # Docs and catalog are optional; without credentials or API nothing works.
    problems = [name for name in ("credentials", "api") if checks.get(name, "ok") != "ok"]
    if problems:
        output["error"] = "Problem with: " + ", ".join(problems)
    return output


def download_docs(docs_file: Path | None) -> str:
    """Reads llms-full.txt – from a local file or from the web."""
    if docs_file:
        return docs_file.read_text(encoding="utf-8")
    response = requests.get(DOCS_FULL_URL, timeout=HTTP_TIMEOUT)
    response.raise_for_status()
    return response.text


def cmd_catalog_update(args: argparse.Namespace) -> dict:
    result = api_request(make_session(), "GET", "/models")
    items = result.get("items", [])
    output = {}
    if result.get("total") and result["total"] > len(items):
        output["warning"] = f"API reports {result['total']} models, but only {len(items)} were returned."
    try:
        docs = catalog.parse_docs(download_docs(args.docs_file))
    except (requests.RequestException, OSError) as error:
        # Works without the docs too – just without parameter details.
        docs = {}
        output["docs_error"] = f"Docs not loaded ({type(error).__name__}), catalog without parameters."
    models = catalog.build_catalog(items, docs)
    write_json_file(CATALOG_FILE, {"updated": date.today().isoformat(), "models": models})
    listed = [m for m in models.values() if m["listed"]]
    return {
        "listed": len(listed),
        "documented": sum(1 for m in listed if m["documented"]),
        "only_in_docs": sorted(slug for slug, m in models.items() if not m["listed"]),
        "file": CATALOG_FILE.name,
        **output,
    }


def estimate_with_learning(session: requests.Session, model_id: str, model: dict,
                           payload: dict, max_tries: int = 5) -> dict:
    """Asks for the price and adds missing required fields automatically.

    The docs do not always list all required fields. If the API reports
    "'video_urls' is a required property", we add a placeholder
    and try again. That way the result also shows the real required fields.
    """
    entry = {"checked": date.today().isoformat()}
    for _ in range(max_tries):  # "_" means: we do not need the loop variable
        try:
            result = api_request(session, "POST", f"/estimate/{model_id}", json_body=payload)
        except CliError as error:
            field = catalog.missing_field(str(error))
            if field and field not in payload:
                spec = model.get("params", {}).get(field, {})
                payload = {**payload, field: catalog.placeholder_value(field, spec)}
                continue
            entry.update(usd=None, error=str(error), payload=payload)
            return entry
        entry.update(usd=result.get("usd"), payload=payload)
        if result.get("pricing_description"):
            entry["pricing"] = result["pricing_description"]
        return entry
    entry.update(usd=None, error=f"Required fields still missing after {max_tries} attempts.", payload=payload)
    return entry


def cmd_prices(args: argparse.Namespace) -> dict:
    models = filtered_models(args)
    if not models:
        raise CliError("No model matches the filters.")
    session = make_session()
    notes = load_models()
    prices = read_json_file(PRICES_FILE, {})
    # Careful: do not call it "error" – main() treats that key as a failure.
    counts = {"usd": 0, "variable": 0, "failed": 0}
    for model_id, model in models.items():
        # Placeholders for required fields plus our tested default values.
        payload = {**catalog.placeholder_payload(model), **notes.get(model_id, {}).get("defaults", {})}
        entry = estimate_with_learning(session, model_id, model, payload)
        prices[model_id] = entry
        if entry.get("usd") is not None:
            counts["usd"] += 1
        elif entry.get("pricing"):
            counts["variable"] += 1
        else:
            counts["failed"] += 1
    write_json_file(PRICES_FILE, prices)
    return {"checked": len(models), **counts, "file": PRICES_FILE.name}


