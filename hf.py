# --- Errors and output ------------------------------------------------------


class CliError(Exception):
    """An expected error: printed as a short message, without a stack trace."""

    def __init__(self, message: str, exit_code: int = 1, status_code: int | None = None):
        super().__init__(message)
        self.exit_code = exit_code
        # The HTTP status of a failed API call, so the server can pass it on unchanged.
        self.status_code = status_code


def print_json(data: dict) -> None:
    """Prints a dictionary as a single line of JSON."""
    # ensure_ascii=False keeps non-ASCII characters readable (ü instead of \u00fc).
    print(json.dumps(data, ensure_ascii=False))


# --- Configuration ----------------------------------------------------------


def load_dotenv(path: Path) -> None:
    """Reads KEY=VALUE lines from a .env file into the environment variables.

    Variables that are already set are not overwritten, i.e. an
    'export HF_API_KEY=...' in the terminal takes precedence over the file.
    """
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        # Skip empty lines, comments and lines without '='.
        if not line or line.startswith("#") or "=" not in line:
            continue
        # split("=", 1) only splits at the first '=' – the secret itself may contain '='.
        name, value = line.split("=", 1)
        name = name.strip().removeprefix("export ").strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(name, value)


def load_credentials() -> tuple[str, str]:
    """Reads key and secret from the environment variables.

    The values are never printed – not even in error messages.
    """
    key = os.environ.get("HF_API_KEY")
    secret = os.environ.get("HF_API_SECRET")
    if not key or not secret:
        raise CliError("HF_API_KEY and HF_API_SECRET must be set.", exit_code=2)
    if key.startswith("your-") or secret.startswith("your-"):
        raise CliError(".env still contains the placeholders from .env.example – enter real values.", exit_code=2)
    return key, secret


def load_models() -> dict:
    """Reads the local model list from models.json."""
    try:
        return json.loads(MODELS_FILE.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        # "from error" keeps the original exception as the cause: hidden normally,
        # but visible in the stack trace with --verbose.
        raise CliError(f"{MODELS_FILE.name} not found.") from error
    except json.JSONDecodeError as error:
        raise CliError(f"{MODELS_FILE.name} is not valid JSON: {error}") from error


def read_json_file(path: Path, default):
    """Reads a JSON file or returns default if it does not exist."""
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise CliError(f"{path.name} is not valid JSON.") from error


def write_json_file(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_catalog() -> dict:
    data = read_json_file(CATALOG_FILE, None)
    if data is None:
        raise CliError("No catalog yet. Run 'hf catalog update' first.")
    return data


def load_history() -> dict:
    """Reads the job log {request_id: job} (empty if it does not exist).

    Older versions only stored the model ID as text. Those entries are
    converted to {"model": ...} so that all entries look the same.
    """
    if not HISTORY_FILE.exists():
        return {}
    try:
        history = json.loads(HISTORY_FILE.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return {request_id: job if isinstance(job, dict) else {"model": job} for request_id, job in history.items()}


def update_job(request_id: str, **fields) -> dict:
    """Merges fields into a job's log entry and returns the updated entry.

    **fields collects all keyword arguments in a dictionary:
    update_job("r1", status="completed") gives fields == {"status": "completed"}.
    In client mode the server keeps the job log, so nothing is written locally.
    """
    if client_settings():
        return {"request_id": request_id, **fields}
    history = load_history()
    job = {**history.get(request_id, {}), **fields}
    history[request_id] = job
    write_json_file(HISTORY_FILE, history)
    return job


def record_status(result: dict) -> None:
    """Stores the status from an API response in the job log."""
    if result.get("request_id") and result.get("status"):
        update_job(result["request_id"], status=result["status"])


# --- Parameters -------------------------------------------------------------


def parse_param(text: str) -> tuple[str, object]:
    """Splits 'key=value' into ('key', value).

    The value is read as JSON if that works: 'duration=5' gives the
    number 5, 'enhance_prompt=true' the boolean True. Everything else stays text.
    """
    if "=" not in text:
        raise CliError(f"Parameter '{text}' is not of the form key=value.")
    key, raw_value = text.split("=", 1)
    try:
        value = json.loads(raw_value)
    except json.JSONDecodeError:
        value = raw_value
    return key.strip(), value


def variants_count(text: str) -> int | str:
    """argparse type for --variants: a positive number or "all"."""
    if text == "all":
        return text
    if not text.isdigit() or int(text) < 1:
        raise argparse.ArgumentTypeError("expected a number >= 1 or 'all'")
    return int(text)


def expand_prompt(args: argparse.Namespace, number: int | str | None = None) -> list[argparse.Namespace]:
    """Resolves {a|b} placeholders in --prompt: one copy of args per chosen variant.

    number=None picks one at random, a number picks that many different ones, "all" every combination.
    Each copy gets the finished prompt plus "template" and "choices", for the job log and the sidecar.
    """
    template = args.prompt
    if not variants.slots(template):
        if number is not None:
            raise CliError("--variants needs placeholders in the prompt, e.g. 'a {red|blue} kite'. Use {a|b}.")
        return [args]
    # getattr with a default: batch lines have no --variant-seed.
    rng = random.Random(getattr(args, "variant_seed", None))
    try:
        if number is None:
            picked = [variants.pick(template, rng)]
        else:
            picked = variants.sample(template, None if number == "all" else number, rng)
    except ValueError as error:
        raise CliError(str(error)) from error
    # vars(args) turns the Namespace into a dict; ** copies it into a new Namespace.
    return [
        argparse.Namespace(**{**vars(args), "prompt": prompt, "template": template, "choices": choices})
        for prompt, choices in picked
    ]


def variant_fields(args: argparse.Namespace) -> dict:
    """{"template": ..., "choices": [...]} if the prompt came from a template, else {}."""
    if getattr(args, "template", None) is None:
        return {}
    return {"template": args.template, "choices": args.choices}


def build_payload(args: argparse.Namespace) -> dict:
    """Builds the JSON body for a generation.

    Order (later ones win): model defaults from models.json,
    then --prompt/--image-url, then --param.
    """
    model_info = load_models().get(args.model_id, {})
    # dict(...) creates a copy so that we do not modify the loaded defaults.
    payload = dict(model_info.get("defaults", {}))
    payload["prompt"] = args.prompt
    if args.image_url and args.from_last_frame:
        raise CliError("Use either --image-url or --from-last-frame, not both.")
    if args.image_url:
        payload["image_url"] = resolve_input_url(args.image_url)
    if args.from_last_frame:
        video = find_video(args.from_last_frame)
        frame = extract_last_frame(video, video.with_name(video.stem + "_last.png"))
        payload["image_url"] = resolve_input_url(str(frame))
    if args.image_urls:
        # A "list comprehension": applies resolve_input_url to every element.
        payload["image_urls"] = [resolve_input_url(value) for value in args.image_urls]
    if args.character:
        payload["custom_reference_id"] = find_character(args.character)["id"]
        payload.setdefault("custom_reference_strength", 1.0)
    for text in args.param:
        key, value = parse_param(text)
        payload[key] = value
    return payload


# --- HTTP -------------------------------------------------------------------


def make_session() -> requests.Session:
    """Creates a session that sends the auth header with every call.

    In client mode the server token is sent instead; the Higgsfield keys stay on the server.
    """
    session = requests.Session()
    settings = client_settings()
    if settings:
        session.headers["Authorization"] = f"Bearer {settings[1]}"
        return session
    key, secret = load_credentials()
    session.headers["Authorization"] = f"Key {key}:{secret}"
    return session


def retry_delay(attempt: int, retry_after: str | None = None) -> float:
    """Wait time before the next attempt: 1, 2, 4 ... seconds plus some randomness.

    If the server sends a Retry-After header, we stick to it.
    """
    if retry_after and retry_after.isdigit():
        return float(retry_after)
    return 2 ** (attempt - 1) + random.uniform(0, 0.5)


def describe_error(response: requests.Response) -> str:
    """Turns an error response into a short, readable message."""
    try:
        detail = response.json().get("detail")
    except (ValueError, AttributeError):
        return response.text[:200] or response.reason
    if isinstance(detail, dict):
        # e.g. {"code": "account_queue_full", "message": "..."}
        return detail.get("message") or json.dumps(detail)
    if isinstance(detail, list):
        # Validation errors: list of {"loc": [...], "msg": "..."}
        parts = []
        for item in detail:
            location = ".".join(str(x) for x in item.get("loc", []) if x not in ("body", ""))
            message = str(item.get("msg", "")).lstrip(": ")
            parts.append(f"{location}: {message}" if location else message)
        return "; ".join(parts)
    # For missing required fields the text starts with ": " (empty field path).
    return str(detail).lstrip(": ")


def client_settings() -> tuple[str, str] | None:
    """(server URL, token) when HF_SERVER is set (client mode), otherwise None (local mode)."""
    server_url = os.environ.get("HF_SERVER")
    if not server_url:
        return None
    token = os.environ.get("HF_SERVER_TOKEN")
    if not token:
        raise CliError("HF_SERVER is set, but HF_SERVER_TOKEN is missing.", exit_code=2)
    return server_url.rstrip("/"), token


def api_base_url() -> str:
    """Where API calls go: Higgsfield itself, or the hf server in client mode."""
    settings = client_settings()
    return settings[0] if settings else BASE_URL


def api_request(
    session: requests.Session,
    method: str,
    path: str,
    json_body: dict | None = None,
    headers: dict | None = None,
) -> dict:
    """Sends an API call and returns the JSON response.

    - Timeout on every call.
    - New attempts on network errors, 429 and 5xx (with backoff).
    - No new attempts on other 4xx – something is wrong with the request.
    """
    url = path if path.startswith("http") else api_base_url() + path
    for attempt in range(1, MAX_ATTEMPTS + 1):
        is_last_attempt = attempt == MAX_ATTEMPTS
        try:
            response = session.request(method, url, json=json_body, headers=headers, timeout=HTTP_TIMEOUT)
        except (requests.ConnectionError, requests.Timeout) as error:
            if is_last_attempt:
                raise CliError(f"Network error after {MAX_ATTEMPTS} attempts: {type(error).__name__}") from error
            time.sleep(retry_delay(attempt))
            continue

        if response.status_code in RETRY_STATUS_CODES and not is_last_attempt:
            time.sleep(retry_delay(attempt, response.headers.get("Retry-After")))
            continue

        if response.status_code >= 400:
            raise CliError(f"HTTP {response.status_code}: {describe_error(response)}", status_code=response.status_code)

        # Some responses (e.g. cancel) have no content.
        return response.json() if response.content else {}

    # Never reached – the loop always ends with return or raise.
    raise CliError("Unexpected error in api_request.")


def download_file(url: str, target: Path) -> None:
    """Downloads a file in chunks (saves memory for large videos).

    Deliberately without the session: the credentials only go to api.higgsfield.ai,
    not to the CDN that hosts the results.
    """
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            # 'with' makes sure the connection is closed safely afterwards.
            with requests.get(url, stream=True, timeout=HTTP_TIMEOUT) as response:
                if response.status_code in RETRY_STATUS_CODES and attempt < MAX_ATTEMPTS:
                    time.sleep(retry_delay(attempt))
                    continue
                if response.status_code >= 400:
                    raise CliError(f"Download failed: HTTP {response.status_code}")
                with target.open("wb") as file:
                    for chunk in response.iter_content(chunk_size=1024 * 1024):
                        file.write(chunk)
                return
        except (requests.ConnectionError, requests.Timeout) as error:
            if attempt == MAX_ATTEMPTS:
                raise CliError(f"Download failed: {type(error).__name__}") from error
            time.sleep(retry_delay(attempt))


# --- Upload -----------------------------------------------------------------


def guess_content_type(path: Path) -> str:
    """Determines the file type from the extension, e.g. .jpg -> image/jpeg."""
    # guess_type returns a tuple (type, encoding) – we do not need the encoding.
    content_type, _ = mimetypes.guess_type(path.name)
    if content_type not in UPLOAD_CONTENT_TYPES:
        allowed = ", ".join(sorted(UPLOAD_CONTENT_TYPES))
        raise CliError(f"File type of '{path.name}' is not supported ({content_type}). Allowed: {allowed}")
    return content_type


def upload_file(session: requests.Session, path: Path) -> str:
    """Uploads a local file to Higgsfield and returns its public URL.

    Flow according to the docs:
    1. Request a presigned upload URL from the API.
    2. Send the file via PUT directly to the storage – with exactly the
       headers from the response and WITHOUT our credentials.
    3. Use the public_url as image_url/video_url in the generation.
    """
    if not path.is_file():
        raise CliError(f"File not found: {path}")
    content_type = guess_content_type(path)
    upload = api_request(session, "POST", "/files/generate-upload-url", json_body={"content_type": content_type})

    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            # requests.put instead of session.put: no Authorization header to the storage.
            response = requests.put(
                upload["upload_url"],
                data=path.read_bytes(),
                headers=upload.get("upload_headers", {}),
                timeout=UPLOAD_TIMEOUT,
            )
        except (requests.ConnectionError, requests.Timeout) as error:
            if attempt == MAX_ATTEMPTS:
                raise CliError(f"Upload failed: {type(error).__name__}") from error
            time.sleep(retry_delay(attempt))
            continue
        if response.status_code in RETRY_STATUS_CODES and attempt < MAX_ATTEMPTS:
            time.sleep(retry_delay(attempt))
            continue
        if response.status_code >= 400:
            raise CliError(f"Upload failed: HTTP {response.status_code}")
        return upload["public_url"]
    raise CliError("Unexpected error in upload_file.")


def resolve_input_url(value: str, session: requests.Session | None = None) -> str:
    """Returns URLs unchanged, uploads local files first."""
    if value.startswith(("http://", "https://")):
        return value
    # expanduser() turns "~/Pictures/x.jpg" into a full path.
    return upload_file(session or make_session(), Path(value).expanduser())


# --- Video helpers (ffmpeg) -------------------------------------------------


def find_video(value: str) -> Path:
    """A video file path, or the downloaded video of a job in the log (by request_id)."""
    path = Path(value).expanduser()
    if path.is_file():
        return path
    if client_settings():
        # In client mode the results live on the server: fetch them into ./outputs first.
        session = make_session()
        record = api_request(session, "GET", f"/v1/jobs/{value}")
        files = fetch_outputs(session, record, {}, Path("outputs"))
        job = {"files": [str(Path(file).resolve()) for file in files]}
    else:
        job = load_history().get(value)
    if job is None:
        raise CliError(f"Video not found: {value}")
    for file in job.get("files", []):
        if gallery.media_kind(file) == "video" and Path(file).is_file():
            return Path(file)
    raise CliError(f"Job {value} has no downloaded video. Run 'hf download {value}' first.")


def run_ffmpeg(arguments: list[str]) -> None:
    """Runs ffmpeg and turns a failure into a short CliError."""
    # shutil.which looks for a program on the PATH, like 'which' in the terminal.
    if shutil.which("ffmpeg") is None:
        raise CliError("ffmpeg not found. Install it, e.g. 'brew install ffmpeg'.")
    # capture_output keeps ffmpeg's long log out of our one-line JSON output.
    completed = subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *arguments], capture_output=True, text=True)
    if completed.returncode != 0:
        # [-300:] keeps only the end of the message, where the actual error is.
        raise CliError(f"ffmpeg failed: {completed.stderr.strip()[-300:]}")


def extract_last_frame(video: Path, target: Path) -> Path:
    """Saves the last frame of a video as an image."""
    # -sseof -0.5 starts reading 0.5 s before the end; -update 1 keeps overwriting
    # the same image, so at the end it holds the very last frame.
    run_ffmpeg(["-sseof", "-0.5", "-i", str(video), "-update", "1", str(target)])
    if not target.is_file():
        raise CliError(f"ffmpeg did not create {target.name}.")
    return target


def concat_list(clips: list[Path]) -> str:
    """The file list for ffmpeg's concat demuxer: one "file '<path>'" line per clip."""
    # A ' inside the path has to be written as '\'' so the quoting stays intact.
    return "".join("file '" + str(clip).replace("'", "'\\''") + "'\n" for clip in clips)


def cmd_concat(args: argparse.Namespace) -> dict:
    clips = [find_video(value).resolve() for value in args.clips]
    if len(clips) < 2:
        raise CliError("concat needs at least two clips.")
    now = datetime.now()
    target = args.out_file or Path("outputs") / f"{now:%Y-%m-%d_%H%M%S}_concat.mp4"
    target.parent.mkdir(parents=True, exist_ok=True)
    # delete=False: we close the file first so ffmpeg can read it, then remove it ourselves.
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8") as listing:
        listing.write(concat_list(clips))
    try:
        # -c copy joins without re-encoding: fast and lossless, but all clips need the same format.
        run_ffmpeg(["-f", "concat", "-safe", "0", "-i", listing.name, "-c", "copy", str(target)])
    except CliError as error:
        raise CliError(f"{error} – concat only works for clips with the same model and settings.") from error
    finally:
        os.unlink(listing.name)
    # kind "local": shows up in the gallery, but 'hf spend' ignores it (nothing was paid).
    update_job(
        f"concat-{now:%Y%m%d-%H%M%S}",
        kind="local",
        model="ffmpeg concat",
        prompt=f"{len(clips)} clips joined: " + ", ".join(clip.name for clip in clips),
        submitted=now.isoformat(timespec="seconds"),
        status="completed",
        files=[str(target.resolve())],
    )
    refresh_gallery(args.open)
    return {"file": str(target), "clips": len(clips)}


