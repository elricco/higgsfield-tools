def cmd_estimate(args: argparse.Namespace) -> dict:
    expanded = expand_prompt(args, args.variants)
    # The price depends on model and parameters, not on the prompt text: one estimate is enough.
    payload = build_payload(expanded[0])
    result = api_request(make_session(), "POST", f"/estimate/{args.model_id}", json_body=payload)
    output = {"model": args.model_id, "usd": result.get("usd"), **variant_fields(expanded[0])}
    output.pop("template", None)
    if args.variants is not None:
        output.pop("choices", None)
        output["variants"] = len(expanded)
        usd = result.get("usd")
        output["estimated_usd"] = round(float(usd) * len(expanded), 3) if usd is not None else None
    # Token-based models return a pricing description instead of a number.
    if result.get("pricing_description"):
        output["pricing"] = result["pricing_description"]
    if args.verbose:
        output["payload"] = payload
        output["response"] = result
    return output


def estimate_cost(session: requests.Session, model_id: str, payload: dict) -> dict:
    """Asks /estimate for the price: {"usd": number or None, "pricing": text or None}."""
    result = api_request(session, "POST", f"/estimate/{model_id}", json_body=payload)
    usd = result.get("usd")
    # The API sends the amount as text ("0.004"); for adding up we need a number.
    return {"usd": float(usd) if usd is not None else None, "pricing": result.get("pricing_description")}


def env_max_usd() -> float | None:
    """The per-job limit from HF_MAX_USD (environment or .env), None if not set."""
    value = os.environ.get(MAX_USD_ENV)
    if not value:
        return None
    try:
        return float(value)
    except ValueError as error:
        raise CliError(f"{MAX_USD_ENV} must be a number, e.g. 0.50 (is '{value}').") from error


def max_usd_limit(args: argparse.Namespace) -> float | None:
    """The cost limit: --max-usd wins, otherwise HF_MAX_USD, otherwise no limit."""
    return args.max_usd if args.max_usd is not None else env_max_usd()


def safe_estimate(session: requests.Session, model_id: str, payload: dict) -> dict:
    """Like estimate_cost, but a failing estimate gives an unknown price instead of an error."""
    try:
        return estimate_cost(session, model_id, payload)
    except CliError as error:
        return {"usd": None, "pricing": None, "estimate_error": str(error)}


def check_budget(cost: dict, max_usd: float | None) -> None:
    """Stops before submitting if the job would cost more than allowed."""
    if max_usd is None:
        return
    if cost["usd"] is None:
        reason = cost["pricing"] or "no estimate available"
        raise CliError(
            f"Price unknown ({reason}), so the limit of ${max_usd:.3f} cannot be checked. Nothing was submitted."
        )
    if cost["usd"] > max_usd:
        raise CliError(
            f"Estimated cost ${cost['usd']:.3f} is above the limit of ${max_usd:.3f}. Nothing was submitted."
        )


def prepare_job(session: requests.Session, args: argparse.Namespace) -> dict:
    """Step 1 of submitting: build the body (uploads local files once) and estimate the price.

    Nothing is paid yet. The result goes to submit_prepared() as is.
    """
    payload = build_payload(args)
    return {"args": args, "payload": payload, "cost": safe_estimate(session, args.model_id, payload)}


def submit_prepared(session: requests.Session, job: dict) -> dict:
    """Step 2 of submitting: send a prepared job and record it in the job log.

    Returns the API response plus "usd" (estimated cost, None if unknown).
    """
    args, payload, cost = job["args"], job["payload"], job["cost"]
    # One idempotency key per job: if api_request repeats the call after a
    # timeout, the server recognizes it and does not create a second (paid) job.
    headers = {"Idempotency-Key": str(uuid.uuid4())}
    result = api_request(session, "POST", f"/{args.model_id}", json_body=payload, headers=headers)
    update_job(
        result["request_id"],
        model=args.model_id,
        prompt=args.prompt,
        payload=payload,
        usd=cost["usd"],
        submitted=datetime.now().isoformat(timespec="seconds"),
        status=result.get("status"),
        **({"from_last_frame": args.from_last_frame} if args.from_last_frame else {}),
        **variant_fields(args),
    )
    return {**result, "usd": cost["usd"]}


def check_prepared_budget(cost: dict, max_usd: float | None) -> None:
    """check_budget, with a clearer message when the estimate itself failed."""
    if max_usd is not None and cost.get("estimate_error"):
        raise CliError(f"Estimate failed, so the limit cannot be checked: {cost['estimate_error']}")
    check_budget(cost, max_usd)


def submit_generation(session: requests.Session, args: argparse.Namespace) -> dict:
    """Prepares one job, checks it against the limit and submits it."""
    job = prepare_job(session, args)
    # Without a limit the estimate is only nice to have; a failing estimate does not block the job.
    check_prepared_budget(job["cost"], max_usd_limit(args))
    return submit_prepared(session, job)


def cmd_submit(args: argparse.Namespace) -> dict:
    (args,) = expand_prompt(args)
    result = submit_generation(make_session(), args)
    choices = {"choices": args.choices} if variant_fields(args) else {}
    return result if args.verbose else {**compact_status(result), "usd": result["usd"], **choices}


def cmd_status(args: argparse.Namespace) -> dict:
    result = api_request(make_session(), "GET", f"/requests/{args.request_id}/status")
    record_status(result)
    if args.verbose:
        return result
    output = compact_status(result)
    if args.urls:
        # Public result URLs, e.g. as --image-url for image-to-video (valid for 7 days).
        output["urls"] = [url for _, url in extract_outputs(result)]
    return output


def cmd_upload(args: argparse.Namespace) -> dict:
    return {"file": str(args.file), "url": upload_file(make_session(), args.file)}


def cmd_cancel(args: argparse.Namespace) -> dict:
    try:
        api_request(make_session(), "POST", f"/requests/{args.request_id}/cancel")
    except CliError as error:
        if str(error).startswith("HTTP 400"):
            # According to the docs: 400 means the job is already running and can no longer be canceled.
            raise CliError(f"Job {args.request_id} is already running and can no longer be canceled.") from error
        raise
    return {"request_id": args.request_id, "status": "canceled"}


def cmd_wait(args: argparse.Namespace) -> dict:
    result = wait_for_job(make_session(), args.request_id, args.timeout)
    return result if args.verbose else compact_status(result)


def cmd_download(args: argparse.Namespace) -> dict:
    session = make_session()
    if client_settings():
        # Give the server a few seconds to finish storing a job that just completed.
        result = api_request(session, "GET", f"/v1/jobs/{args.request_id}?wait=10")
    else:
        result = api_request(session, "GET", f"/requests/{args.request_id}/status")
        record_status(result)
    if result.get("status") != "completed":
        output = compact_status(result)
        output.setdefault("error", f"Job is not finished yet (status '{result.get('status')}').")
        return output
    job = load_history().get(args.request_id, {})
    files = fetch_outputs(session, result, job, args.out)
    refresh_gallery(args.open)
    return {"request_id": args.request_id, "status": "completed", "files": files}


def cmd_run(args: argparse.Namespace) -> dict:
    if args.variants is not None:
        return run_variants(args)
    (args,) = expand_prompt(args)
    choices = {"choices": args.choices} if variant_fields(args) else {}
    session = make_session()
    submitted = submit_generation(session, args)
    result = wait_for_job(session, submitted["request_id"], args.timeout)
    if result.get("status") != "completed":
        return {**compact_status(result), **choices}
    job = load_history().get(result["request_id"], {})
    files = fetch_outputs(session, result, job, args.out)
    refresh_gallery(args.open)
    return {
        "request_id": result["request_id"],
        "status": "completed",
        "files": files,
        "usd": submitted["usd"],
        **choices,
    }


def run_variants(args: argparse.Namespace) -> dict:
    """hf run --variants: several variants of one template, in parallel like a batch."""
    expanded = expand_prompt(args, args.variants)
    session = make_session()
    jobs = [prepare_job(session, single) for single in expanded]
    # --max-usd is the limit for all variants together; HF_MAX_USD still applies to each one.
    check_many_budget(jobs, args.max_usd)
    entries = run_many(session, jobs, args.timeout, args.out)
    for single, entry in zip(expanded, entries, strict=True):
        entry["choices"] = single.choices
    refresh_gallery(args.open)
    return {"jobs": entries, **summarize_many(entries)}


def total_cost(jobs: list[dict]) -> dict:
    """The summed cost of prepared jobs; unknown as soon as one price is unknown."""
    unknown = [job for job in jobs if job["cost"]["usd"] is None]
    if unknown:
        reasons = {job["cost"].get("pricing") or job["cost"].get("estimate_error") or "no estimate" for job in unknown}
        return {"usd": None, "pricing": f"{len(unknown)} of {len(jobs)} jobs: " + "; ".join(sorted(reasons))}
    return {"usd": round(sum(job["cost"]["usd"] for job in jobs), 3), "pricing": None}


def check_many_budget(jobs: list[dict], max_usd_total: float | None) -> None:
    """--max-usd applies to all jobs together, HF_MAX_USD to each single job."""
    check_budget(total_cost(jobs), max_usd_total)
    per_job = env_max_usd()
    for job in jobs:
        check_prepared_budget(job["cost"], per_job)


def run_many(session: requests.Session, jobs: list[dict], timeout: int, out_dir: Path) -> list[dict]:
    """Submits several prepared jobs, waits for all of them and downloads the results.

    All jobs are submitted first, so Higgsfield works on them at the same time.
    A failing job does not stop the others; it gets an "error" entry instead.
    """
    entries = []
    for job in jobs:
        try:
            submitted = submit_prepared(session, job)
            entries.append({"request_id": submitted["request_id"], "usd": submitted["usd"]})
        except CliError as error:
            entries.append({"error": str(error)})
    for entry in entries:
        if "error" in entry:
            continue
        try:
            result = wait_for_job(session, entry["request_id"], timeout)
            entry["status"] = result.get("status")
            if entry["status"] == "completed":
                entry["files"] = fetch_outputs(session, result, load_history().get(entry["request_id"], {}), out_dir)
            else:
                entry["error"] = compact_status(result)["error"]
        except CliError as error:
            entry["error"] = str(error)
    return entries


def summarize_many(entries: list[dict]) -> dict:
    """Total cost and an overall "error" if at least one job failed."""
    output = {"usd": round(sum(entry.get("usd") or 0 for entry in entries), 3)}
    failed = sum(1 for entry in entries if "error" in entry)
    if failed:
        output["error"] = f"{failed} of {len(entries)} jobs failed."
    return output


def view_args(view: str, base_url: str, args: argparse.Namespace) -> argparse.Namespace:
    """The arguments for one view, as if typed as 'hf run ...'."""
    prompt = " ".join(part for part in (CHARACTER_VIEWS[view], args.details, VIEWS_KEEP) if part)
    return argparse.Namespace(
        model_id=args.model,
        prompt=prompt,
        image_url=None,
        image_urls=[base_url],
        character=None,
        param=list(VIEWS_PARAMS),
        max_usd=None,
        from_last_frame=None,
    )


def cmd_character_views(args: argparse.Namespace) -> dict:
    """Creates the views for a Soul ID training from one base portrait."""
    session = make_session()
    # Upload once, then all views use the same URL.
    base_url = resolve_input_url(args.base, session)
    jobs = [prepare_job(session, view_args(view, base_url, args)) for view in args.views]
    # Check the price for all views together before anything is submitted.
    check_many_budget(jobs, args.max_usd)
    entries = run_many(session, jobs, args.timeout, args.out)
    # strict=True raises an error if the two lists ever have different lengths.
    for view, entry in zip(args.views, entries, strict=True):
        entry["view"] = view
    refresh_gallery(args.open)
    return {"base": str(args.base), "views": entries, **summarize_many(entries)}


# Fields allowed in one line of a batch file.
BATCH_FIELDS = {"model", "prompt", "params", "image_url", "image_urls", "character", "from_last_frame"}


def batch_job_args(data: dict, default_model: str | None, line_number: int) -> argparse.Namespace:
    """Turns one line of a batch file into the same arguments 'hf run' would get."""
    unknown = set(data) - BATCH_FIELDS
    if unknown:
        raise CliError(
            f"Line {line_number}: unknown field(s) {', '.join(sorted(unknown))}. "
            f"Allowed: {', '.join(sorted(BATCH_FIELDS))}"
        )
    model = data.get("model") or default_model
    if not model or not data.get("prompt"):
        raise CliError(f"Line {line_number}: 'prompt' and 'model' (or --model) are required.")
    # json.dumps keeps the type: 5 stays a number, "16:9" stays text, when parse_param reads it back.
    params = [f"{key}={json.dumps(value)}" for key, value in data.get("params", {}).items()]
    return argparse.Namespace(
        model_id=model,
        prompt=data["prompt"],
        image_url=data.get("image_url"),
        image_urls=data.get("image_urls"),
        character=data.get("character"),
        param=params,
        max_usd=None,
        from_last_frame=data.get("from_last_frame"),
    )


def read_batch_file(path: Path, default_model: str | None) -> list[argparse.Namespace]:
    """Reads a JSON Lines file: one job per line, empty lines and lines starting with # are skipped."""
    if not path.is_file():
        raise CliError(f"File not found: {path}")
    jobs = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        try:
            data = json.loads(line)
        except json.JSONDecodeError as error:
            raise CliError(f"Line {line_number}: not valid JSON ({error.msg}).") from error
        if not isinstance(data, dict):
            raise CliError(f"Line {line_number}: expected a JSON object {{...}}.")
        # A line with {a|b} placeholders gets one random variant.
        jobs.extend(expand_prompt(batch_job_args(data, default_model, line_number)))
    if not jobs:
        raise CliError(f"{path.name} contains no jobs.")
    return jobs


def cmd_batch(args: argparse.Namespace) -> dict:
    """Runs all jobs of a batch file in parallel, after checking the total cost."""
    job_args = read_batch_file(args.file, args.model)
    session = make_session()
    jobs = [prepare_job(session, single) for single in job_args]
    if args.dry_run:
        return {
            "jobs": [
                {
                    "model": job["args"].model_id,
                    "prompt": job["args"].prompt[:60],
                    "usd": job["cost"]["usd"],
                    **({"pricing": job["cost"]["pricing"]} if job["cost"].get("pricing") else {}),
                }
                for job in jobs
            ],
            "estimated_usd": total_cost(jobs)["usd"],
        }
    # --max-usd is the limit for the whole batch here; HF_MAX_USD still applies to each job.
    check_many_budget(jobs, args.max_usd)
    entries = run_many(session, jobs, args.timeout, args.out)
    refresh_gallery(args.open)
    return {"jobs": entries, **summarize_many(entries)}


def spend_since(days: int | None) -> str | None:
    """The first day to count: --days 1 means today, --days 7 the last seven days including today."""
    return (date.today() - timedelta(days=days - 1)).isoformat() if days else None


def summarize_spend(jobs: Iterable[dict], since: str | None) -> dict:
    """Adds up the estimated costs of finished jobs (from the local log or the server's store)."""
    total = 0.0
    by_model = {}
    counts = {"jobs": 0, "running": 0, "not_charged": 0, "price_unknown": 0, "untracked": 0}
    for job in jobs:
        if job.get("kind") == "local":
            continue  # e.g. concat: made on this machine, nothing was paid
        submitted = job.get("submitted")
        if not submitted:
            # Entries from before the job log existed: no price, no date.
            counts["untracked"] += 1
            continue
        # ISO dates compare correctly as text: "2026-10-29" < "2026-10-30".
        if since and submitted[:10] < since:
            continue
        status = job.get("status")
        if status in NOT_CHARGED_STATUSES:
            counts["not_charged"] += 1
        elif status != "completed":
            counts["running"] += 1
        elif job.get("usd") is None:
            counts["price_unknown"] += 1
        else:
            counts["jobs"] += 1
            total += job["usd"]
            by_model[job["model"]] = by_model.get(job["model"], 0) + job["usd"]
    return {
        "estimated_usd": round(total, 3),
        # Most expensive models first.
        "by_model": {model: round(usd, 3) for model, usd in sorted(by_model.items(), key=lambda item: -item[1])},
        **counts,
    }


def cmd_spend(args: argparse.Namespace) -> dict:
    if client_settings():
        query = f"?days={args.days}" if args.days else ""
        return api_request(make_session(), "GET", f"/v1/spend{query}")
    since = spend_since(args.days)
    return {"since": since or "all", **summarize_spend(load_history().values(), since)}


def gallery_items() -> tuple[list[dict], int]:
    """Jobs from the log whose files still exist, newest first, plus the number of missing files."""
    items = []
    missing = 0
    for request_id, job in load_history().items():
        files = [path for path in job.get("files", []) if Path(path).is_file()]
        missing += len(job.get("files", [])) - len(files)
        if not files:
            continue
        # Old entries have no "submitted" – then the file's modification time has to do.
        submitted = job.get("submitted") or datetime.fromtimestamp(Path(files[0]).stat().st_mtime).isoformat(
            timespec="seconds"
        )
        items.append(
            {
                **job,
                "request_id": request_id,
                "files": files,
                "submitted": submitted,
                "date": submitted[:16].replace("T", " "),
            }
        )
    items.sort(key=lambda item: item["submitted"], reverse=True)
    return items, missing


def write_gallery() -> dict:
    items, missing = gallery_items()
    page = gallery.render_gallery(items, datetime.now().strftime("%Y-%m-%d %H:%M"))
    GALLERY_FILE.write_text(page, encoding="utf-8")
    return {"file": str(GALLERY_FILE), "jobs": len(items), "missing_files": missing}


def refresh_gallery(open_browser: bool = False) -> None:
    """Rebuilds the gallery after a download. A gallery problem must never fail the job itself."""
    if client_settings():
        return  # the job log is on the server; a served gallery is planned for later
    try:
        write_gallery()
    except OSError:
        return
    if open_browser:
        webbrowser.open(GALLERY_FILE.as_uri())


def scan_for_results(directory: Path) -> int:
    """Adds result files in a folder to the job log, matched by the request_id in the file name.

    Useful for files that were downloaded before the job log existed.
    """
    history = load_history()
    added = 0
    # rglob("*") walks through the folder and all subfolders.
    for path in sorted(directory.expanduser().rglob("*")):
        request_id = gallery.find_request_id(path.name)
        if not path.is_file() or not gallery.media_kind(path.name) or request_id not in history:
            continue
        files = history[request_id].setdefault("files", [])
        if str(path.resolve()) not in files:
            files.append(str(path.resolve()))
            added += 1
    write_json_file(HISTORY_FILE, history)
    return added


