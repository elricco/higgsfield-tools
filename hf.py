def compact_status(result: dict) -> dict:
    """Reduces a status response to the important fields."""
    output = {"request_id": result.get("request_id"), "status": result.get("status")}
    if result.get("error"):
        output["error"] = result["error"]
    elif result.get("status") in NOT_CHARGED_STATUSES:
        # So that main() returns a non-zero exit code.
        output["error"] = f"Job ended with status '{result['status']}'"
    return output


def extract_outputs(result: dict) -> list[tuple[str, str]]:
    """Collects all result URLs as a list of (field name, url).

    Images come as a list ("images"), videos as a single object ("video").
    "audio" and "audios" can contain the same file – duplicates are dropped.
    """
    outputs = []
    seen = set()
    for field in ("images", "video", "audio", "audios"):
        value = result.get(field)
        if not value:
            continue
        # Wrap a single object in a list so that both cases work the same way.
        items = value if isinstance(value, list) else [value]
        for item in items:
            url = item.get("url")
            if url and url not in seen:
                seen.add(url)
                outputs.append((field, url))
    return outputs


def output_filename(model_id: str, request_id: str, field: str, url: str, index: int, total: int, day: date) -> str:
    """Builds the file name: <date>_<model>_<request_id>[_<n>].<extension>"""
    model_slug = model_id.replace("/", "-")
    extension = Path(urlparse(url).path).suffix or FALLBACK_EXTENSIONS.get(field, "")
    number = f"_{index}" if total > 1 else ""
    return f"{day:%Y-%m-%d}_{model_slug}_{request_id}{number}{extension}"


def poll_until_done(session: requests.Session, request_id: str, timeout: int) -> dict:
    """Polls the status until the job is finished or the time runs out."""
    # time.monotonic() is a clock that never jumps backwards – ideal for measuring time.
    deadline = time.monotonic() + timeout
    delay = POLL_START_DELAY
    while True:
        result = api_request(session, "GET", f"/requests/{request_id}/status")
        if result.get("status") in TERMINAL_STATUSES:
            return result
        if time.monotonic() + delay > deadline:
            raise CliError(
                f"Timeout after {timeout} s, job {request_id} is still running "
                f"(status '{result.get('status')}'). Continue later with 'wait'."
            )
        # Some randomness (jitter) so that many clients do not poll in lockstep.
        time.sleep(delay + random.uniform(0, 0.5))
        delay = min(delay * 1.5, POLL_MAX_DELAY)


def sidecar_data(request_id: str, job: dict, file_name: str) -> dict:
    """What we write next to each result: everything needed to understand or repeat it."""
    return {
        "file": file_name,
        "request_id": request_id,
        "model": job.get("model"),
        "prompt": job.get("prompt"),
        **({"template": job["template"], "choices": job.get("choices")} if job.get("template") else {}),
        "payload": job.get("payload"),
        "usd": job.get("usd"),
        "submitted": job.get("submitted"),
        "downloaded": datetime.now().isoformat(timespec="seconds"),
    }


def download_outputs(result: dict, job: dict, out_dir: Path) -> list[Path]:
    """Downloads all results and writes a .json sidecar per file. Does not touch the job log."""
    outputs = extract_outputs(result)
    if not outputs:
        raise CliError("The response contains no result files.")
    request_id = result["request_id"]
    # parents=True also creates intermediate folders, exist_ok=True ignores existing ones.
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    # enumerate(..., start=1) yields number and element: (1, a), (2, b), ...
    for index, (field, url) in enumerate(outputs, start=1):
        name = output_filename(job.get("model") or "unknown", request_id, field, url, index, len(outputs), date.today())
        target = out_dir / name
        download_file(url, target)
        # with_suffix swaps the extension: x.png -> x.json
        write_json_file(target.with_suffix(".json"), sidecar_data(request_id, job, name))
        paths.append(target)
    return paths


def save_outputs(result: dict, job: dict, out_dir: Path) -> list[str]:
    """Downloads all results with sidecars, records them in the job log and returns the file paths."""
    paths = download_outputs(result, job, out_dir)
    # resolve() gives the absolute path, so the log works from any folder.
    update_job(result["request_id"], status="completed", files=[str(path.resolve()) for path in paths])
    return [str(path) for path in paths]


def is_settled(record: dict) -> bool:
    """A server job record will not change any more: finished and stored (or cannot be)."""
    if record.get("status") not in TERMINAL_STATUSES:
        return False
    return bool(record.get("stored") or record.get("status") != "completed" or record.get("download_error"))


def wait_for_job(session: requests.Session, request_id: str, timeout: int) -> dict:
    """Waits until a job is finished. Locally by polling Higgsfield, in client mode by asking the server."""
    if not client_settings():
        result = poll_until_done(session, request_id, timeout)
        record_status(result)
        return result
    deadline = time.monotonic() + timeout
    while True:
        remaining = deadline - time.monotonic()
        # The server holds each request until the job is done, at most "wait" seconds.
        # 25 s stays below HTTP_TIMEOUT, so the request itself never times out.
        wait = max(1, min(25, int(remaining)))
        record = api_request(session, "GET", f"/v1/jobs/{request_id}?wait={wait}")
        if is_settled(record):
            return record
        if time.monotonic() >= deadline:
            raise CliError(
                f"Timeout after {timeout} s, job {request_id} is still running "
                f"(status '{record.get('status')}'). Continue later with 'wait'."
            )


def download_server_file(session: requests.Session, rel: str, target: Path) -> None:
    """Downloads one stored file from the hf server (with the server token).

    Writes to "<name>.part" first and renames it at the end, so a broken download never
    leaves a half file behind that looks complete.
    """
    url = f"{api_base_url()}/v1/files/{quote(rel)}"
    partial = target.with_name(target.name + ".part")
    for attempt in range(1, MAX_ATTEMPTS + 1):
        try:
            with session.get(url, stream=True, timeout=HTTP_TIMEOUT) as response:
                if response.status_code in RETRY_STATUS_CODES and attempt < MAX_ATTEMPTS:
                    time.sleep(retry_delay(attempt))
                    continue
                if response.status_code >= 400:
                    raise CliError(f"Download from the server failed: HTTP {response.status_code}")
                with partial.open("wb") as file:
                    for chunk in response.iter_content(chunk_size=1024 * 1024):
                        file.write(chunk)
            # replace() renames in one step: the target is either complete or not there at all.
            partial.replace(target)
            return
        except requests.RequestException as error:
            partial.unlink(missing_ok=True)
            if attempt == MAX_ATTEMPTS:
                raise CliError(f"Download from the server failed: {type(error).__name__}") from error
            time.sleep(retry_delay(attempt))


def fetch_outputs(session: requests.Session, result: dict, job: dict, out_dir: Path) -> list[str]:
    """Puts the result files into out_dir: from Higgsfield locally, from the server in client mode."""
    if not client_settings():
        return save_outputs(result, job, out_dir)
    if result.get("download_error"):
        raise CliError(f"The server could not store the result: {result['download_error']}")
    if not result.get("stored") or not result.get("files"):
        raise CliError(f"The server has not stored job {result.get('request_id')} yet. Try again shortly.")
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for rel in result["files"]:
        target = out_dir / Path(rel).name
        download_server_file(session, rel, target)
        # The sidecar has the same name with .json (written by the server).
        download_server_file(session, str(Path(rel).with_suffix(".json")), target.with_suffix(".json"))
        paths.append(str(target))
    return paths


